class NoCacheForAuthenticatedPagesMiddleware:
    """Prevent browsers from caching authenticated HTML responses.

    This helps avoid showing a stale protected page after logout when the user
    navigates back in the browser.
    """

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)

        if getattr(request, 'user', None) and request.user.is_authenticated:
            response['Cache-Control'] = 'no-store, no-cache, must-revalidate, max-age=0'
            response['Pragma'] = 'no-cache'
            response['Expires'] = '0'

        return response